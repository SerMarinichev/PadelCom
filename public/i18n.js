const LANG_STORAGE_KEY = "padelcom_lang";
const LANG_LABELS = { ru: "Русский", uz: "O'zbekcha", en: "English" };

function getStoredLanguage(fallback) {
  try {
    const stored = typeof localStorage !== "undefined" ? localStorage.getItem(LANG_STORAGE_KEY) : null;
    if (stored && translations[stored]) return stored;
  } catch { /* localStorage unavailable */ }
  return fallback && translations[fallback] ? fallback : "ru";
}

function setStoredLanguage(lang) {
  try { if (typeof localStorage !== "undefined") localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* ignore */ }
}

function translate(lang, key) {
  const dict = translations[lang] || translations.ru;
  return dict[key] ?? translations.ru[key] ?? key;
}

export { translations, LANG_STORAGE_KEY, LANG_LABELS, getStoredLanguage, setStoredLanguage, translate };
